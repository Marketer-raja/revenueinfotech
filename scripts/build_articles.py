#!/usr/bin/env python3
"""Build public article pages from manually approved Newsdesk entries."""
from __future__ import annotations
import html
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://revenueinfotech.com"
MIN_BODY_CHARS = 600
MARKER = "<!-- Generated by RevenueInfoTech build_articles.py. Do not edit this file manually. -->"


def esc(value: object) -> str:
    return html.escape(str(value or ""), quote=True)


def slugify(value: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", value.lower().strip()).strip("-")
    return value[:80].strip("-") or "technology-news"


def safe_http_url(value: str) -> bool:
    try:
        parsed = urlparse(value)
        return parsed.scheme in {"http", "https"} and bool(parsed.netloc)
    except Exception:
        return False


def paragraphs(body: str) -> str:
    blocks = re.split(r"\n\s*\n", body.strip())
    return "\n".join(f"<p>{esc(block).replace(chr(10), '<br>')}</p>" for block in blocks if block.strip())


def article_html(item: dict, slug: str) -> str:
    title = esc(item.get("title"))
    summary = esc(item.get("summary"))
    author_name = str(item.get("author") or "RevenueInfoTech Editorial Desk")
    author_type = "Organization" if author_name.lower() == "revenueinfotech editorial desk" else "Person"
    author = esc(author_name)
    category = esc(item.get("category") or "Technology News")
    source = esc(item.get("source"))
    source_url = str(item.get("url", "")).split(",")[0].strip()
    source_link = f'<a href="{esc(source_url)}" rel="noopener noreferrer">{source}</a>' if safe_http_url(source_url) else source
    extra = [u for u in item.get("sources", []) if isinstance(u,str) and safe_http_url(u) and u != source_url]
    source_link += "".join(f' · <a href="{esc(u)}" rel="noopener noreferrer">{esc(u)}</a>' for u in extra)
    published = item.get("published") or datetime.now(timezone.utc).isoformat()
    try:
        dt = datetime.fromisoformat(str(published).replace("Z", "+00:00"))
        published_iso = dt.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")
        published_display = dt.strftime("%B %d, %Y")
    except Exception:
        published_iso = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
        published_display = "Recently published"
    url = f"{SITE}/articles/{slug}/"
    body_html = paragraphs(str(item.get("articleBody", "")))
    image = str(item.get("image", ""))
    image_html = f'<figure><img src="{esc(image)}" alt="{title}" loading="lazy"><figcaption>Editorial illustration or image provided by the editor.</figcaption></figure>' if safe_http_url(image) else ""
    schema = {
        "@context": "https://schema.org", "@type": "NewsArticle",
        "mainEntityOfPage": {"@type": "WebPage", "@id": url},
        "headline": str(item.get("title", ""))[:110],
        "description": str(item.get("summary", ""))[:300],
        "datePublished": published_iso, "dateModified": published_iso,
        "author": {"@type": author_type, "name": author_name},
        "publisher": {"@type": "Organization", "name": "RevenueInfoTech", "url": SITE},
    }
    if safe_http_url(image):
        schema["image"] = [image]
    schema_json = json.dumps(schema, ensure_ascii=False).replace("</", "<\\/")
    return f'''{MARKER}
<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} | RevenueInfoTech</title><meta name="description" content="{summary}"><link rel="canonical" href="{url}"><meta name="robots" content="index,follow,max-image-preview:large">
<meta property="og:type" content="article"><meta property="og:title" content="{title}"><meta property="og:description" content="{summary}"><meta property="og:url" content="{url}">
{f'<meta property="og:image" content="{esc(image)}">' if safe_http_url(image) else ''}
<meta property="article:published_time" content="{published_iso}"><script type="application/ld+json">{schema_json}</script>
<style>*{{box-sizing:border-box}}body{{margin:0;color:#172033;font:17px/1.8 system-ui,-apple-system,Segoe UI,Arial,sans-serif}}header,main,footer{{max-width:820px;margin:auto;padding:20px}}header{{border-bottom:1px solid #e5e7eb}}a{{color:#2457c5}}.meta{{color:#64748b;font-size:14px}}h1{{font-size:clamp(30px,5vw,44px);line-height:1.2;letter-spacing:-.03em}}main{{padding-top:34px;padding-bottom:54px}}.summary{{font-size:20px;color:#475569;border-left:3px solid #2563eb;padding-left:16px}}figure{{margin:28px 0}}figure img{{width:100%;height:auto;border-radius:12px}}figcaption{{font-size:12px;color:#64748b}}.article-body p{{margin:0 0 22px}}.source{{border-top:1px solid #e5e7eb;padding-top:18px;margin-top:36px;font-size:14px}}footer{{border-top:1px solid #e5e7eb;color:#64748b;font-size:13px}}</style>
</head><body><header><a href="/">RevenueInfoTech</a> · <a href="/articles/">Technology Articles</a></header>
<main><p class="meta">{category} · {published_display}</p><h1>{title}</h1><p class="meta">By {author}</p><p class="summary">{summary}</p>{image_html}<article class="article-body">{body_html}</article>
<div class="source"><strong>Source and further reading:</strong> {source_link}. This article is prepared by RevenueInfoTech based on the linked source and editorial review. See our <a href="/editorial-ethics.html">editorial standards</a>.</div>
<p><a href="/articles/">← All articles</a> · <a href="/">Home</a></p></main><footer><a href="/about.html">About</a> · <a href="/contact.html">Contact</a> · <a href="/privacy-policy.html">Privacy Policy</a></footer></body></html>\n'''


def main() -> None:
    data_path = ROOT / "home-news.json"
    if not data_path.exists():
        raise SystemExit("home-news.json is missing; no approved articles can be built")
    data = json.loads(data_path.read_text(encoding="utf-8"))
    published: dict[str, dict] = {}
    for item in data.get("items", []):
        body = str(item.get("articleBody", "")).strip()
        if len(body) < MIN_BODY_CHARS or not str(item.get("author", "")).strip():
            continue
        if not str(item.get("title", "")).strip() or not str(item.get("summary", "")).strip():
            continue
        if not safe_http_url(str(item.get("url", ""))):
            continue
        slug = slugify(str(item.get("slug") or item.get("title") or item.get("id") or "story"))
        if slug in published:
            slug = f"{slug}-{slugify(str(item.get('id') or 'story'))[:12]}"
        published[slug] = item

    articles_root = ROOT / "articles"
    articles_root.mkdir(exist_ok=True)
    for slug, item in published.items():
        folder = articles_root / slug
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "index.html").write_text(article_html(item, slug), encoding="utf-8")

    # Delete only pages generated by this script when their item is no longer approved.
    for page in articles_root.glob("*/index.html"):
        if page.parent.name not in published:
            try:
                if MARKER in page.read_text(encoding="utf-8"):
                    page.unlink()
                    try: page.parent.rmdir()
                    except OSError: pass
            except OSError:
                pass

    archive_rows = []
    for slug, item in sorted(published.items(), key=lambda pair: str(pair[1].get("published", "")), reverse=True):
        try:
            date_label = datetime.fromisoformat(str(item.get("published", "")).replace("Z", "+00:00")).strftime("%B %d, %Y")
        except Exception:
            date_label = "Recently published"
        archive_rows.append(
            f'<article><p class="meta">{esc(item.get("category") or "Technology News")} · {esc(date_label)}</p>'
            f'<h2><a href="/articles/{slug}/">{esc(item.get("title"))}</a></h2>'
            f'<p>{esc(item.get("summary"))}</p><p class="meta">By {esc(item.get("author"))}</p></article>'
        )
    archive_content = "".join(archive_rows) or "<p>New articles will appear here after editorial review and publication.</p>"
    archive_html = f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Technology News & Editorial Articles | RevenueInfoTech</title><meta name="description" content="Original technology news and editorial articles reviewed by RevenueInfoTech."><link rel="canonical" href="{SITE}/articles/"><meta name="robots" content="index,follow"><style>body{{max-width:850px;margin:0 auto;padding:24px;font:16px/1.7 system-ui,Arial,sans-serif;color:#172033}}a{{color:#2457c5}}header,footer{{padding:12px 0;border-bottom:1px solid #e5e7eb}}article{{padding:20px 0;border-bottom:1px solid #e5e7eb}}h1{{font-size:32px}}h2{{font-size:22px;line-height:1.3;margin:4px 0}}.meta{{font-size:13px;color:#64748b;margin:0 0 5px}}</style></head><body><header><a href="/">RevenueInfoTech</a></header><main><h1>Technology News & Editorial Articles</h1><p>Original articles reviewed and approved by the RevenueInfoTech editorial desk.</p>{archive_content}</main><footer><a href="/about.html">About</a> · <a href="/editorial-ethics.html">Editorial standards</a> · <a href="/contact.html">Contact</a></footer></body></html>'''
    (articles_root / "index.html").write_text(archive_html, encoding="utf-8")

    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    static = [
        ("/", "daily", "1.0"), ("/articles/", "daily", "0.8"),
        ("/about.html", "yearly", "0.5"), ("/editorial-ethics.html", "yearly", "0.5"),
        ("/peer-review-process.html", "yearly", "0.5"), ("/sponsorship-disclosure.html", "yearly", "0.4"),
        ("/contact.html", "yearly", "0.4"), ("/privacy-policy.html", "yearly", "0.3"),
        ("/terms-of-service.html", "yearly", "0.3"),
    ]
    urls = [f'<url><loc>{SITE}{path}</loc><lastmod>{today}</lastmod><changefreq>{freq}</changefreq><priority>{priority}</priority></url>' for path, freq, priority in static]
    for slug in published:
        urls.append(f'<url><loc>{SITE}/articles/{slug}/</loc><lastmod>{today}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>')
    sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join(urls) + '\n</urlset>\n'
    (ROOT / "sitemap.xml").write_text(sitemap, encoding="utf-8")
    print(f"Built {len(published)} approved article page(s), article archive, and {len(urls)} sitemap URL(s).")

if __name__ == "__main__":
    main()
