/* RevenueInfoTech: automatically display fresh news on every SPA section page.
   Data is generated by scripts/fetch_news.py and refreshed by GitHub Actions. */
(() => {
  "use strict";
  const DATA_URL = "/news.json";
  const PANEL_ID = "rit-auto-news-panel";
  const STYLE_ID = "rit-auto-news-style";
  let cachedItems = null;
  let lastPath = "";

  const routeInfo = () => {
    const path = (location.pathname || "/").toLowerCase().replace(/\/+$/, "") || "/";
    if (path === "/") return null; // Home already has its own automated news modules.
    if (path === "/admin") return null;
    if (path === "/tutorials") return {
      title: "Latest Developer & Tutorial Updates",
      intro: "Fresh software, web development, AI and programming updates to help guide your next tutorial.",
      categories: ["Software Development", "Web Development", "Artificial Intelligence", "Cloud Computing"]
    };
    if (path === "/reviews") return {
      title: "Latest Product & Technology Updates",
      intro: "Recent technology developments to keep in mind when researching products and reviews.",
      categories: null
    };
    if (path === "/comparisons") return {
      title: "Latest Technology Updates",
      intro: "Recent developments across the technology landscape.",
      categories: null
    };
    if (path === "/buying-guides") return {
      title: "Latest Product & Buying News",
      intro: "Fresh device, software and technology updates for readers comparing their options.",
      categories: null
    };
    if (path === "/news") return {
      title: "Latest Technology News",
      intro: "Automatically refreshed headlines from technology publishers. Open the original source for the full story.",
      categories: null
    };
    if (path === "/categories" || path.startsWith("/category/")) return {
      title: "Latest Technology News",
      intro: "More recent technology headlines from across our coverage areas.",
      categories: null
    };
    if (path.startsWith("/article/")) return {
      title: "More Recent Technology News",
      intro: "Keep up with the latest developments alongside this article.",
      categories: null
    };
    return {
      title: "Latest Technology News & Updates",
      intro: "Fresh headlines from technology publishers, updated automatically.",
      categories: null
    };
  };

  function addStyles() {
    if (document.getElementById(STYLE_ID)) return;
    const style = document.createElement("style");
    style.id = STYLE_ID;
    style.textContent = `
      #${PANEL_ID}{box-sizing:border-box;width:min(1120px,calc(100% - 40px));margin:36px auto 48px;padding:26px 0 8px;border-top:1px solid #e5e7eb;color:#111827;font-family:Inter,system-ui,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}
      #${PANEL_ID} *{box-sizing:border-box}
      #${PANEL_ID} .rit-news-heading{font-size:clamp(22px,3vw,30px);line-height:1.2;margin:0 0 8px;font-weight:800;letter-spacing:-.025em}
      #${PANEL_ID} .rit-news-intro{margin:0 0 20px;color:#6b7280;font-size:14px;line-height:1.6}
      #${PANEL_ID} .rit-news-grid{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:16px}
      #${PANEL_ID} .rit-news-card{min-width:0;overflow:hidden;border:1px solid #e5e7eb;border-radius:14px;background:#fff;display:flex;flex-direction:column}
      #${PANEL_ID} .rit-news-card img{width:100%;height:155px;object-fit:cover;background:#f3f4f6}
      #${PANEL_ID} .rit-news-card-body{padding:15px;display:flex;flex:1;flex-direction:column;align-items:flex-start}
      #${PANEL_ID} .rit-news-meta{font-size:11px;color:#6b7280;margin:0 0 8px;text-transform:uppercase;letter-spacing:.04em}
      #${PANEL_ID} .rit-news-card h3{font-size:16px;line-height:1.45;margin:0 0 9px;font-weight:750}
      #${PANEL_ID} .rit-news-card h3 a{color:#111827;text-decoration:none}
      #${PANEL_ID} .rit-news-card h3 a:hover{color:#2563eb}
      #${PANEL_ID} .rit-news-summary{font-size:13px;line-height:1.6;color:#4b5563;margin:0 0 14px}
      #${PANEL_ID} .rit-news-read{margin-top:auto;color:#2563eb;font-size:13px;font-weight:700;text-decoration:none}
      #${PANEL_ID} .rit-news-updated{font-size:11px;color:#9ca3af;margin-top:14px}
      @media(max-width:760px){#${PANEL_ID} .rit-news-grid{grid-template-columns:repeat(2,minmax(0,1fr))}#${PANEL_ID} .rit-news-card img{height:130px}}
      @media(max-width:520px){#${PANEL_ID}{width:calc(100% - 28px);margin:28px auto 36px;padding-top:22px}#${PANEL_ID} .rit-news-grid{grid-template-columns:1fr}#${PANEL_ID} .rit-news-card{display:grid;grid-template-columns:112px minmax(0,1fr)}#${PANEL_ID} .rit-news-card img{height:100%;min-height:140px}#${PANEL_ID} .rit-news-card-body{padding:12px}#${PANEL_ID} .rit-news-card h3{font-size:14px}#${PANEL_ID} .rit-news-summary{font-size:12px}}
    `;
    document.head.appendChild(style);
  }

  function safeDate(value) {
    if (!value) return "";
    const d = new Date(value);
    return Number.isNaN(d.getTime()) ? "" : d.toLocaleDateString(undefined, {year:"numeric",month:"short",day:"numeric"});
  }
  function make(tag, cls, text) {
    const el = document.createElement(tag);
    if (cls) el.className = cls;
    if (text !== undefined) el.textContent = text;
    return el;
  }
  function buildPanel(info, items, updated) {
    const panel = make("section");
    panel.id = PANEL_ID;
    panel.setAttribute("aria-label", info.title);
    panel.append(make("h2", "rit-news-heading", info.title));
    panel.append(make("p", "rit-news-intro", info.intro));
    const grid = make("div", "rit-news-grid");
    let filtered = items || [];
    if (info.categories) {
      const preferred = filtered.filter(item => info.categories.includes(item.category));
      if (preferred.length >= 3) filtered = preferred;
    }
    filtered = filtered.slice(0, 6);
    if (!filtered.length) {
      grid.append(make("p", "", "News is temporarily unavailable. Please check again soon."));
    }
    filtered.forEach(item => {
      const card = make("article", "rit-news-card");
      if (item.image && /^https?:\/\//i.test(item.image)) {
        const img = document.createElement("img");
        img.src = item.image;
        img.alt = "";
        img.loading = "lazy";
        img.referrerPolicy = "no-referrer";
        img.onerror = () => img.remove();
        card.append(img);
      }
      const body = make("div", "rit-news-card-body");
      body.append(make("p", "rit-news-meta", [item.source, item.category, safeDate(item.published)].filter(Boolean).join(" · ")));
      const heading = make("h3");
      const link = document.createElement("a");
      link.href = item.url;
      link.target = "_blank";
      link.rel = "noopener noreferrer";
      link.textContent = item.title || "Read the latest technology update";
      heading.append(link);
      body.append(heading);
      if (item.excerpt) body.append(make("p", "rit-news-summary", item.excerpt));
      const read = document.createElement("a");
      read.className = "rit-news-read";
      read.href = item.url;
      read.target = "_blank";
      read.rel = "noopener noreferrer";
      read.textContent = "Read at source ↗";
      body.append(read);
      card.append(body);
      grid.append(card);
    });
    panel.append(grid);
    if (updated) panel.append(make("p", "rit-news-updated", "Feed updated: " + safeDate(updated) + " · Headlines link to their original publishers."));
    return panel;
  }

  async function loadItems() {
    if (cachedItems) return cachedItems;
    const response = await fetch(DATA_URL, {cache:"no-store"});
    if (!response.ok) throw new Error("Could not load news feed");
    const data = await response.json();
    cachedItems = Array.isArray(data.items) ? data.items : [];
    return cachedItems;
  }

  async function render() {
    const info = routeInfo();
    const old = document.getElementById(PANEL_ID);
    if (!info) { if (old) old.remove(); lastPath = location.pathname; return; }
    if (lastPath === location.pathname && old) return;
    lastPath = location.pathname;
    addStyles();
    try {
      const items = await loadItems();
      const data = await (async () => {
        try {
          const r = await fetch(DATA_URL, {cache:"no-store"});
          return r.ok ? r.json() : {};
        } catch (_) { return {}; }
      })();
      const panel = buildPanel(info, items, data.updated);
      const existing = document.getElementById(PANEL_ID);
      if (existing) existing.replaceWith(panel);
      else {
        const footer = document.querySelector("body > footer.site-footer");
        document.body.insertBefore(panel, footer || null);
      }
    } catch (error) {
      console.warn("[RevenueInfoTech] Auto news could not load:", error);
    }
  }

  function scheduleRender() { window.setTimeout(render, 250); }
  document.addEventListener("DOMContentLoaded", scheduleRender);
  window.addEventListener("popstate", scheduleRender);
  // React routes can change without a full page load.
  const observer = new MutationObserver(() => {
    if (location.pathname !== lastPath) scheduleRender();
  });
  observer.observe(document.documentElement, {childList:true, subtree:true});
  // Also cover cases where this script runs after DOMContentLoaded.
  if (document.readyState !== "loading") scheduleRender();
})();
